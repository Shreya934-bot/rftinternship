import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns


data = {
    "Movie_Name": [
        "Inception",
        "Avengers",
        "Interstellar",
        "Joker",
        "Titanic"
    ],
    "Rating": [8.8, 8.5, 8.7, 8.4, 7.9],
    "Genre": [
        "Sci-Fi",
        "Action",
        "Sci-Fi",
        "Drama",
        "Romance"
    ],
    "Revenue": [
        850,
        1500,
        700,
        1000,
        2200
    ]
}

df = pd.DataFrame(data)
print("\n Movie Dataset:\n")
print(df)
highest_rated = df[df["Rating"] == df["Rating"].max()]
print("\n Highest Rated Movie:\n")
print(highest_rated)
genre_revenue = df.groupby("Genre")["Revenue"].sum()
print("\n Revenue by Genre:\n")
print(genre_revenue)
top_movies = df.sort_values(by="Revenue", ascending=False).head(5)

print("\n Top Movies by Revenue:\n")
print(top_movies)

sns.set_style("whitegrid")
plt.figure(figsize=(5, 3))
sns.barplot(
    x=genre_revenue.index,
    y=genre_revenue.values
)
plt.title(" Genre vs Revenue")
plt.xlabel("Genre")
plt.ylabel("Revenue")
plt.tight_layout()
plt.savefig("genre_vs_revenue.png")
plt.show()
plt.figure(figsize=(5, 3))
sns.histplot(
    df["Rating"],
    kde=True,
    bins=5
)
plt.title(" Rating Distribution")
plt.xlabel("Rating")
plt.ylabel("Frequency")
plt.tight_layout()
plt.savefig("rating_distribution.png")
plt.show()
correlation = df["Rating"].corr(df["Revenue"])
print("\n Correlation between Rating & Revenue:")
print(round(correlation, 2))
best_movie = highest_rated["Movie_Name"].values[0]
best_genre = genre_revenue.idxmax()
print("\n Key Insights:")
print(f" Highest Rated Movie: {best_movie}")
print(f" Most Profitable Genre: {best_genre}")
print(f" Average Rating: {df['Rating'].mean():.2f}")
print(f" Total Revenue: {df['Revenue'].sum()} Million")